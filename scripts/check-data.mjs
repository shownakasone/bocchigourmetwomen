// データの整合性チェック（重複・住所と市町村のずれ・座標の範囲など）。使い方: npm run check
import fs from 'node:fs';
import { load } from 'js-yaml';
const V = JSON.parse(fs.readFileSync('data/videos.json','utf8'));
const S = load(fs.readFileSync('data/shops.yaml','utf8'));
const P = new Set(JSON.parse(fs.readFileSync('data/processed.json','utf8')));
const vm = new Map(V.map(v=>[v.videoId,v]));
const out = (k, a) => console.log(`${a.length ? '⚠' : '✓'} ${k}: ${a.length}`, a.slice(0,8));
out('動画 重複ID', V.filter((v,i)=>V.findIndex(w=>w.videoId===v.videoId)!==i).map(v=>v.videoId));
out('動画 タイトル/日付が空', V.filter(v=>!v.title||!v.publishedAt).map(v=>v.videoId));
out('動画 長さ0', V.filter(v=>/^PT0M0S$/.test(v.duration)).map(v=>v.videoId+' '+v.title.slice(0,20)));
out('動画 未処理(お店抽出してない)', V.filter(v=>!P.has(v.videoId)).map(v=>v.videoId));
out('処理済みだが動画一覧にない', [...P].filter(id=>!vm.has(id)));
out('お店 重複ID', S.filter((s,i)=>S.findIndex(t=>t.id===s.id)!==i).map(s=>s.id));
const key = s => s.name.replace(/[（(].*?[）)]|\s/g,'')+'|'+s.city;
out('お店 同名同市（重複の疑い）', S.filter((s,i)=>S.findIndex(t=>key(t)===key(s))!==i).map(s=>s.name+' '+s.city));
out('お店 訪問なし', S.filter(s=>!s.visits?.length).map(s=>s.name));
out('訪問の動画が一覧にない', S.flatMap(s=>(s.visits??[]).filter(v=>!vm.has(v.videoId)).map(v=>s.name+' '+v.videoId)));
out('同じお店に同じ動画が2回', S.filter(s=>new Set(s.visits.map(v=>v.videoId)).size!==s.visits.length).map(s=>s.name));
out('座標なし', S.filter(s=>s.lat==null && !s.nomap).map(s=>s.name));
const box = {青森県:[40.2,41.6,139.8,141.7],岩手県:[38.7,40.5,140.6,142.1],秋田県:[38.8,40.6,139.6,141.0]};
out('座標が県の外', S.filter(s=>s.lat!=null&&box[s.pref]&&!(s.lat>=box[s.pref][0]&&s.lat<=box[s.pref][1]&&s.lng>=box[s.pref][2]&&s.lng<=box[s.pref][3])).map(s=>`${s.name} ${s.pref} ${s.lat},${s.lng}`));
out('住所と県が違う', S.filter(s=>s.address&&/[都道府県]/.test(s.address)&&!s.address.replace(/^〒?[\d-]+\s*/,'').startsWith(s.pref)).map(s=>`${s.name} ${s.pref} / ${s.address}`));
out('住所と市町村が違う', S.filter(s=>s.address&&s.city&&s.address.includes(s.pref)&&!s.address.includes(s.city.replace(/^.+郡/,''))).map(s=>`${s.name} ${s.city} / ${s.address}`));
out('ジャンル空', S.filter(s=>!s.genre).map(s=>s.name));
out('県空', S.filter(s=>!s.pref).map(s=>s.name));
out('価格が変（0以下/10万以上）', S.flatMap(s=>s.visits.flatMap(v=>(v.menu??[]).filter(m=>m.price!=null&&(m.price<=0||m.price>=100000)).map(m=>s.name+' '+m.name+' '+m.price))));
const shopVideos = new Set(S.flatMap(s=>s.visits.map(v=>v.videoId)));
console.log('— 動画', V.length, '本 / お店のある動画', shopVideos.size, '本 / お店', S.filter(s=>!s.draft).length, '件（閉店', S.filter(s=>s.closed).length, '・おおよその位置', S.filter(s=>s.approx).length, '）');
console.log('— 最新3本', V.slice(0,3).map(v=>v.publishedAt.slice(0,10)+' '+v.title.slice(0,18)));
